//Tipos de dados Primitivos em JavaScript
//String, Number, Boolean, Null, Undefined, Symbol

let numero = 10; // Number
let valor = 20.10; //
let texto = "Kalleb Carvalho"; // String


// Para saber o tipo de dado de uma variável, podemos utilizar o operador typeof.
console.log(typeof numero);
console.log(typeof valor);
console.log(typeof texto);

// Boolean é um tipo de dado que só pode ter dois valores: true ou false.
let verdadeiro = true;
let falso = false;
console.log(verdadeiro);


// Undefined é um tipo de dado que indica que uma variável não possui um valor atribuído.
let indefinido; // Undefined
console.log(indefinido);

//Null é um tipo de dado que indica que uma variável não possui um valor atribuído, 
//Mas que foi intencionalmente definido como nulo.

let anular = null; // Null

console.log(anular);