//Variável do tipo constante é uma variável que não pode ter seu valor alterado após ser declarado.
//LET é diferente de VAR, pois não permite que a variável seja redeclarada, apenas alterada.
//Var é uma variável que pode ser redeclarada e alterada a qualquer momento.

let valor = 1000; // Number

valor = 2000; // Alterando o valor da variável
valor = "Eu sou o Kalleb Carvalho"; // Alterando o valor da variável para String

console.log(valor); // Exibindo o valor da variável

// Variável do tipo constante é uma variável que não pode ter seu valor alterado após ser declarado.

const PI = 3.14; // Number
console.log(PI); // Exibindo o valor da constante

// PI = 1000; Exemplo de erro, pois não é possível alterar o valor de uma constante
