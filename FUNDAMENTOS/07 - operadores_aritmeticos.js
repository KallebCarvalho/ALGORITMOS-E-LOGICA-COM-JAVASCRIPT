//Operadores matemáticos

//Adição (+)
let resultadoSoma = 10 + 5; // Number
console.log(resultadoSoma); // Exibindo o resultado da soma

//Subtração (-)
let resultadoSubtracao = 10 - 5;
console.log(resultadoSubtracao); // Exibindo o resultado da subtração

//Multiplicação (*)
let resultadoMultiplicacao = 10 * 5;
console.log(resultadoMultiplicacao); // Exibindo o resultado da multiplicação

//Divisão (/)
let resultadoDivisao = 10 / 5;
console.log(resultadoDivisao); // Exibindo o resultado da divisão

//Módulo (%) - Pega o resto da divisão do primeiro número pelo segundo número.
let resultadoModulo = 10 % 5;
console.log(resultadoModulo); // Exibindo o resultado do módulo

//Incremento (++) - Ou seja adiciona 1 ao valor da variável.
let numero = 10;
numero++;
console.log(numero); // Exibindo o resultado do incremento

//Decremento (--) - Ou seja subtrai 1 ao valor da variável.
let numero2 = 10;
numero2--;
console.log(numero2); // Exibindo o resultado do decremento

//Exponenciação (**) - Ou seja eleva o primeiro número pelo segundo número.
let resultadoExponenciacao = 10 ** 5; // São dois asteriscos, ou seja, 10 elevado a 5.
console.log(resultadoExponenciacao); // Exibindo o resultado da exponenciação