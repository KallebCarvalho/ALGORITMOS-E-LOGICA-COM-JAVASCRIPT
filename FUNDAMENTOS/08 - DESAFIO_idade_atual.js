//Neste desafio a ideia é calcular a idade atual de uma pessoa,
// A partir do ano de nascimento e do ano atual.

var anoNascimento = 1997; // Number
var anoAtual = 2026; // Number

var idadeAtual = anoAtual - anoNascimento; // Number
console.log("A minha idade atual é:" + idadeAtual + " anos"); 
// Concatenando a string com a variável idadeAtual
// Ou fazer uso de template string, que é uma forma mais moderna de concatenar strings com variáveis.
//exemplo de template string:
console.log(`A minha idade atual é: ${idadeAtual} anos`); // Usar crases invertidas (``) 
