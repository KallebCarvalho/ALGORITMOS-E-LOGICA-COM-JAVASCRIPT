//Neste desafio vamos fazer a conversão de horas para minutos e segundos, a partir de um valor em horas.
//utilizando operadores aritméticos.

var horas = 1; // Number
var minutos = horas * 60; // Number
var segundos = horas * 3600; // Number
console.log(`${horas} horas equivalem a ${minutos} minutos e ${segundos} segundos.`);
