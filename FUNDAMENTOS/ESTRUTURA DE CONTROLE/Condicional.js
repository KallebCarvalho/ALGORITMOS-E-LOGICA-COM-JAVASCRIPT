// Condicional "SE" (IF) 
// Estrutura de controle que permite executar um bloco de código se uma condição for verdadeira

//Se (if) a idade for maior ou igual a 18
// então execute o bloco de código dentro das chaves
//BLOCO DE CÓDIGO é tudo que está dentro das chaves {}

const idade = 15;
if (idade >= 18) {
    console.log("Você é maior de idade.");
}
//Se (if) a idade for menor que 18
// então execute o bloco de código dentro das chaves
const idade2 = 16;
if (idade2 < 18) {
    console.log("Você é menor de idade.");
}