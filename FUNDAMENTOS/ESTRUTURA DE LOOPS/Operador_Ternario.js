//Operador Ternário (?:)
//Operador Ternário é reconhecido pelo símbolo ?:

let media = 8;
media >= 8 ? console.log("Aluno aprovado") : console.log("Aluno reprovado");

//Explicação:
//Se a media do aluno for maior ou igual a 8, 
// o código dentro do ? : é executado, caso contrário, o código dentro do : é executado.
//Logo o aluno aprovado é exibido.
//caso a media do aluno fosse menor que 8
//O proximo código será executado, logo o aluno reprovado é exibido.
