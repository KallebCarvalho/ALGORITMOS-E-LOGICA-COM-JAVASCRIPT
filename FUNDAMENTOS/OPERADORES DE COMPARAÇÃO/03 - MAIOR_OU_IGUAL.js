//Apredendo sobre operadores de comparação

//Maior que (>) - Compara se o valor da esquerda é maior que o valor da direita.

var numero17 = 100; // Number
var numero18 = 200; // Number
console.log(numero17 > numero18); 
// false - O valor da esquerda é menor que o valor da direita (100 < 200)

var numero19 = 200; // Number
var numero20 = 50; // Number
console.log(numero19 > numero20);
// true - O valor da esquerda é maior que o valor da direita (200 > 50)

// Maior ou igual (>=) - Compara se o valor da esquerda é maior ou igual ao valor da direita.

var numero21 = 100; // Number
var numero22 = 100; // Number
console.log(numero21 >= numero22);
// true - O valor da esquerda é igual ao valor da direita (100 = 100)