//Apredendo sobre operadores de comparação
// Aprendendo sobre o operador de comparação "Menor ou Igual" (<=)

var numero23 = 50; // Number
var numero24 = 100; // Number
console.log(numero23 <= numero24);
// true - O valor da esquerda é menor que o valor da direita (50 < 100)

var numero23 = 200; // Number
var numero24 = 100; // Number
console.log(numero23 <= numero24);
// false - O valor da esquerda é maior que o valor da direita (200 > 100)
