//Operador lógico AND (&&)
//Retorna true se ambos os valores forem true, caso contrário retorna false

const valor1 = true;
const valor2 = false;
console.log(valor1 && valor2);// falso - Um dos valores é false, então o resultado é false

const valor3 = true;
const valor4 = true;
console.log(valor3 && valor4);// verdadeiro - Ambos os valores são true, então o resultado é true