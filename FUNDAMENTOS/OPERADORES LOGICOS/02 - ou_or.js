//Operador logico OU OR (||)
//Retorna true se pelo menos um dos valores for true, caso contrário retorna false

var valor1 = true;
var valor2 = false;
console.log(valor1 || valor2);// verdadeiro - Um dos valores é true, então o resultado é true

var valor3 = false;
var valor4 = false;
console.log(valor3 || valor4); // Falso - ambos os valores são false, então o resultado é false.

