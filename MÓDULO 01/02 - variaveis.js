/* Variável é um espaço na memória do computador usado para guardar dados temporários. */
//É como se fosse uma caixa que guardamos coisas dentro.
//E podemos colocar e retirar coisas dessa caixa a qualquer momento.

//Variável do tipo constante é uma variável que não pode ter seu valor alterado após ser declarado.
//LET é diferente de VAR, pois não permite que a variável seja redeclarada, apenas alterada.
//Var é uma variável que pode ser redeclarada e alterada a qualquer momento.


var nome = "Kalleb Carvalho"; // String
var idade = 29; // Number
var altura = 1.75; // Number
 
// Utilizando  var em javascript para declarar variáveis, 
// podemos alterar o valor da variável a qualquer momento.
// Podemos também utilizar o let para declarar variáveis, 
// Mas com a diferença de que o let não permite que a variável seja redeclarada, apenas alterada.

let cidade = "Campo Grande"; // String
let estado = "Mato Grosso do Sul"; // String
let bairro = "Pioneiros"; // String


